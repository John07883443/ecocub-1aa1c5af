#!/usr/bin/env bash
#
# Активация новой сборки на VPS. Эталонная версия — сервер должен исполнять
# именно её (обычно как /home/deploy/deploy.sh).
#
# Раньше сборка шла здесь же: npm install + npm run build на машине с 2 ГБ
# памяти, из которых сборке отдавалось 1.5 ГБ. Она проходила впритык и
# однажды упала бы на боевом сервере. Теперь собирает GitHub Actions, а сюда
# по rsync приезжает готовый .output — этому скрипту остаётся подменить
# каталог и перезапустить процесс.
#
# Скрипт идемпотентен и безопасен для повторного запуска: при любой неудаче
# возвращается предыдущая сборка.

set -euo pipefail

APP_DIR=/var/www/ecocub
INCOMING=/home/deploy/incoming/output
PM2_NAME=ecocub
PM2_CONFIG=/home/deploy/ecosystem.config.cjs
HEALTH_URL=http://127.0.0.1:3000/
HEALTH_TRIES=15
LEADS_DIR=/var/lib/ecocub

log() { printf '[deploy] %s\n' "$*"; }
fail() { printf '[deploy] ОШИБКА: %s\n' "$*" >&2; exit 1; }

# --------------------------------------------------------------------
# Проверки до того, как трогать работающий сайт
# --------------------------------------------------------------------

[ -d "$INCOMING" ] || fail "нет каталога со сборкой: $INCOMING"
[ -f "$INCOMING/server/index.mjs" ] || fail "в сборке нет server/index.mjs"

# Цель сборки. Конфиг подставляет воркер для Cloudflare, если не задано иное,
# а такой артефакт под Node молча завершается, не открывая порт. Actions это
# уже проверяет, но выкладку могли запустить и вручную.
grep -q '"preset": "node-server"' "$INCOMING/nitro.json" \
  || fail "сборка не под Node (ожидался preset node-server)"

# Каталог базы заявок. Создаётся здесь, а не руками: иначе после пересоздания
# сервера заявки молча уходили бы только в Telegram, а база оставалась пустой.
#
# Строго `sudo -n`. Обычный sudo в неинтерактивной сессии по ssh не падает,
# а ждёт ввода пароля — деплой завис бы насмерть, причём ровно на свежей
# машине, ради которой этот блок и написан. Права deploy на sudo урезаны
# несколькими командами, поэтому неудача здесь ожидаема и не должна ронять
# выкладку: сайт поднимется, заявки продолжат уходить в Telegram, а починку
# видно в логе.
if [ ! -d "$LEADS_DIR" ]; then
  if sudo -n mkdir -p "$LEADS_DIR" 2>/dev/null \
    && sudo -n chown deploy:deploy "$LEADS_DIR" 2>/dev/null \
    && sudo -n chmod 750 "$LEADS_DIR" 2>/dev/null; then
    log "создал каталог базы заявок $LEADS_DIR"
  else
    log "ВНИМАНИЕ: каталога $LEADS_DIR нет, а создать его не вышло (нужен sudo без пароля)."
    log "ВНИМАНИЕ: сайт поднимется, но заявки будут уходить ТОЛЬКО в Telegram, в базу — нет."
    log "Исправить одной строкой от root:"
    log "  mkdir -p $LEADS_DIR && chown deploy:deploy $LEADS_DIR && chmod 750 $LEADS_DIR"
  fi
fi

# --------------------------------------------------------------------
# Обновление репозитория
# --------------------------------------------------------------------
#
# Код сайта приезжает собранным, но серверу нужны и файлы из репозитория —
# например scripts/leads-export.mjs. Ветка приводится к origin/main жёстко:
# любые случайные правки на боевой машине не должны переживать выкладку.

cd "$APP_DIR"
log "обновляю репозиторий"
git fetch --prune origin main
git reset --hard origin/main

# --------------------------------------------------------------------
# Подмена сборки
# --------------------------------------------------------------------

log "откладываю текущую сборку в .output.prev"
rm -rf "$APP_DIR/.output.prev"
[ -d "$APP_DIR/.output" ] && cp -a "$APP_DIR/.output" "$APP_DIR/.output.prev"

log "переношу новую сборку"
rsync -a --delete "$INCOMING/" "$APP_DIR/.output/"

# --------------------------------------------------------------------
# Запуск
# --------------------------------------------------------------------
#
# start-or-reload: определение процесса раньше жило только в сохранённом
# состоянии pm2. Потеря этого состояния означала, что `pm2 reload` падает
# с «процесс не найден», а поднимать приходится руками, по памяти.
#
# Перезапуск делается ПО ФАЙЛУ КОНФИГА, а не по имени процесса. Разница не
# косметическая: по имени pm2 не перечитывает ecosystem.config.cjs, то есть не
# выполняет заново readEnvFile('/home/deploy/ecocub.env'), и подмешивает
# окружение текущей оболочки. Новые переменные до приложения не доезжают даже
# после полной выкладки — деплой зелёный, в логах пусто, а process.env пуст.
# Проверено на живом сервере 10.08.2026: после reload по имени в
# /proc/<pid>/environ новых переменных не оказалось, старые остались с
# первого старта по конфигу.

if pm2 describe "$PM2_NAME" > /dev/null 2>&1; then
  log "перезапускаю процесс"
  pm2 reload "$PM2_CONFIG" --update-env > /dev/null
else
  log "процесса нет — запускаю по конфигу"
  pm2 start "$PM2_CONFIG" > /dev/null
fi
pm2 save > /dev/null

# --------------------------------------------------------------------
# Проверка и откат
# --------------------------------------------------------------------

log "жду ответа сайта"
healthy=0
for _ in $(seq 1 "$HEALTH_TRIES"); do
  sleep 2
  if curl -sf -o /dev/null --max-time 5 "$HEALTH_URL"; then healthy=1; break; fi
done

if [ "$healthy" = "1" ]; then
  log "готово, сайт отвечает"
  exit 0
fi

log "сайт не отвечает — возвращаю предыдущую сборку"
if [ -d "$APP_DIR/.output.prev" ]; then
  rsync -a --delete "$APP_DIR/.output.prev/" "$APP_DIR/.output/"
  pm2 reload "$PM2_CONFIG" --update-env > /dev/null || pm2 start "$PM2_CONFIG" > /dev/null
  for _ in $(seq 1 "$HEALTH_TRIES"); do
    sleep 2
    if curl -sf -o /dev/null --max-time 5 "$HEALTH_URL"; then
      fail "новая сборка не поднялась, откат выполнен — сайт работает на предыдущей версии"
    fi
  done
  fail "новая сборка не поднялась, откат выполнен, но сайт всё ещё не отвечает — нужны руки"
fi

fail "новая сборка не поднялась, откатываться не на что — нужны руки"
