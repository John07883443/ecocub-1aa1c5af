/**
 * Типы стандарта проектирования EcoCub.
 *
 * Зачем нужен отдельный слой. Числа продукта — сторона модуля, толщина стены,
 * высота потолка — до сих пор жили россыпью по конструктору, презентациям и
 * текстам сайта. Проверить их было не с чем: единственным источником правды
 * оставался архитектурный альбом в PDF, который код не читает.
 *
 * Здесь альбом переведён в данные. Каждое число несёт ссылку на лист, с
 * которого оно снято, и признак достоверности: подтверждено чертежом,
 * выведено расчётом или требует проверки архитектором. Ничего «примерно» и
 * ничего «по памяти».
 *
 * Единицы. Линейные размеры — в миллиметрах и целые: так их печатает
 * архитектор, и так они не теряют точность при делении пополам (3420 / 2 =
 * 1710, а 3,42 / 2 в двоичной плавающей точке — уже нет). Площади — в м².
 */

/** Миллиметры, целое число. Базовая единица всех линейных размеров. */
export type Mm = number;

/**
 * Откуда взято число.
 *
 * `album` — снято с листа архитектурного альбома, лист указан в `sheet`.
 * `derived` — вычислено из значений `album` (и проверяется тестами).
 * `needs-review` — прочитано с чертежа, но привязка не подтверждена
 * архитектором. Такие значения нельзя использовать в расчётах для клиента.
 */
export type Confidence = "album" | "derived" | "needs-review";

/** Ссылка на источник: альбом, лист, что именно на нём показано. */
export interface SourceRef {
  /** Идентификатор документа из `DOCUMENTS`. */
  doc: string;
  /** Номер листа в альбоме. */
  sheet?: number;
  /** Название листа — чтобы искать глазами, а не считать страницы. */
  title?: string;
}

/** Габариты и состав одного модуля. */
export interface ModuleStandard {
  id: string;
  /** Наружный габарит по ширине (короткая сторона в плане). */
  externalWidthMm: Mm;
  /** Наружный габарит по глубине (длинная сторона в плане). */
  externalDepthMm: Mm;
  /** Толщина наружной стены модуля. Одна на все четыре грани. */
  wallThicknessMm: Mm;
  /** Чистый размер внутри стен по ширине. */
  clearWidthMm: Mm;
  /** Чистый размер внутри стен по глубине. */
  clearDepthMm: Mm;
  /** Толщина плиты пола. */
  floorSlabMm: Mm;
  /** Высота помещения в чистоте — продуктовая константа 3150. */
  clearHeightMm: Mm;
  /** Толщина плиты кровли. */
  roofSlabMm: Mm;
  /** Полная высота модуля: пол + чистая высота + кровля. */
  totalHeightMm: Mm;
  source: SourceRef;
}

/**
 * Вариант проёма. Высота считается от чистого пола (отметка 0.000).
 *
 * Ширина здесь не задаётся намеренно: по альбому подтверждаются высоты
 * (они читаются с размерных цепочек по вертикали однозначно), а ширины
 * привязаны к конкретной грани конкретного модуля и живут в `faces`.
 */
export interface OpeningHeightVariant {
  id: string;
  /** Высота проёма от пола, мм. */
  heightMm: Mm;
  /** Сколько глухой стены остаётся над проёмом до плиты кровли. */
  headroomMm: Mm;
  label: string;
  confidence: Confidence;
  source: SourceRef;
}

/**
 * Размерная цепочка одной грани модуля (развёртка Р-1…Р-4).
 *
 * Хранится дословно, как на листе: сумма отрезков равна габариту грани, и
 * тест это проверяет. Разбор «какой отрезок — проём, а какой — простенок»
 * оставлен архитектору: с одной размерной цепочки это не следует, а гадать
 * в стандарте нельзя.
 */
export interface ModuleFace {
  /** Обозначение развёртки на листе: Р-1 … Р-4. */
  id: string;
  /** Габарит грани: ширина модуля или его глубина. */
  spanMm: Mm;
  /** Отрезки по горизонтали, слева направо, как проставлены на листе. */
  chainMm: Mm[];
  /** Высота проёма на этой грани, если он на ней есть. */
  openingHeightMm?: Mm;
  confidence: Confidence;
}

/** Один из четырёх модулей проекта: грани и назначение. */
export interface ModuleInstance {
  /** Буква модуля в альбоме: A, B, C, D. */
  id: string;
  /** Положение левого нижнего угла наружного габарита, мм. */
  xMm: Mm;
  yMm: Mm;
  /**
   * Модуль повёрнут на 90°: длинная сторона 3420 идёт вдоль X, короткая 3200
   * вдоль Y. Поворот — не косметика: он меняет, какая грань смотрит наружу и
   * какое остекление на ней возможно.
   */
  rotated?: boolean;
  /** Помещения, попадающие в этот модуль. */
  roomIds: string[];
  faces: ModuleFace[];
  source: SourceRef;
}

/** Высотная отметка на фасаде. */
export interface LevelMark {
  /** Отметка в метрах, как подписана на фасаде. */
  m: number;
  label: string;
  confidence: Confidence;
}

/** Помещение с площадью из экспликации. */
export interface RoomEntry {
  id: string;
  no: number;
  name: string;
  areaM2: number;
}

/**
 * Способ считать площадь.
 *
 * У проекта их четыре, и они дают четыре разных числа: 34,17 / 43,8 / 55 / 80.
 * Пока способ не назван, спор о площади бессмысленен, поэтому каждый способ
 * здесь описан отдельно и снабжён формулой.
 */
export interface AreaDefinition {
  id: string;
  label: string;
  /** Значение для Weekend One, м². */
  valueM2: number;
  /** Как получается это число — человеческим языком. */
  formula: string;
  confidence: Confidence;
  source: SourceRef;
}

/** Правило планировки, вычитанное из проекта. */
export interface PlanningRule {
  id: string;
  rule: string;
  /** Чем подтверждается на Weekend One. */
  evidence: string;
  confidence: Confidence;
}

/** Стыковка двух соседних модулей. */
export type JointKind = "shared-wall" | "back-to-back";

export interface Joint {
  a: string;
  b: string;
  kind: JointKind;
  /** Суммарная толщина стены в стыке. */
  thicknessMm: Mm;
}
