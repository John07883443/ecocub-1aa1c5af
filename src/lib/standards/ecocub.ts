/**
 * Почему подписанные площади не сходятся с расчётом до сотых.
 *
 * Объяснение получено от владельца продукта, и оно снимает почти все
 * расхождения, которые иначе выглядели бы ошибкой обмера.
 *
 * Первое: в стыках модулей стены снимаются, и полоса, которую они занимали,
 * становится полом. Помещение из двух модулей больше суммы двух модулей — на
 * 0,63 м² при общей стене и на 1,26 м² при стыке спина к спине. Это считается
 * функцией `openedJointGainM2`, а не списывается на погрешность.
 *
 * Второе: толщина стены при отливке гуляет в пределах производственного
 * допуска, и на доме из четырёх-восьми модулей это набегает на десятые доли
 * квадратного метра.
 *
 * Практическое следствие: сходимость проверяется с допуском, а не до точного
 * равенства. Требовать точного совпадения от заводского изделия — значит
 * получить красное на ровном месте и начать подгонять габарит модуля под
 * округление в экспликации.
 */
