/** 130000 → «130 тыс. ₽/м²» (неразрывные пробелы, чтобы не рвалось в выдаче). */
export function priceThousandsLabel(perM2: number): string {
  const k = Math.round(perM2 / 1000);
  return `${k}\u00a0тыс.\u00a0₽/м²`;
}

export const priceLabel = priceThousandsLabel(START_PRICE_PER_M2_RUB);

/** 150000 → «150 000» (неразрывный пробел между разрядами). */
export function formatRubSpaced(n: number): string {
  return String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, "\u00a0");
}

